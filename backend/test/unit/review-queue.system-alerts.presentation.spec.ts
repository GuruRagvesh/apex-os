/**
 * The review queue screen's half of the system-alert contract.
 *
 * The pure rules in frontend/components/attendance/review-queue-presentation.ts
 * run here directly; the component is checked at the source level for the
 * things that only exist in markup (badge, columns, buttons, responsive
 * classes). The backend vocabulary is checked against the frontend so a
 * renamed label cannot silently drift.
 */
import { readFileSync } from 'fs';
import { resolve } from 'path';
import {
  activeFilterCount,
  actionLabels,
  DEFAULT_FILTERS,
  filterQueueItems,
  queueOrigin,
  statusLabel,
  statusOptions,
  subjectName,
  SYSTEM_COLUMNS,
  SYSTEM_REQUESTS_FILTER,
  SYSTEM_REQUESTS_LABEL,
  USER_REQUEST_TYPES,
  type PresentableItem,
} from '../../../frontend/components/attendance/review-queue-presentation';
import { REVIEW_TYPE_LABEL } from '../../src/modules/platform/review-queue/review-queue.types';

const FRONTEND = resolve(__dirname, '../../../frontend/components/attendance');
const component = readFileSync(resolve(FRONTEND, 'UnifiedReviewQueue.tsx'), 'utf8');
const api = readFileSync(resolve(FRONTEND, 'review-queue-api.ts'), 'utf8');

const request = (id: string, name: string, extra: Partial<PresentableItem> = {}): PresentableItem & { id: string } => ({
  id, requestType: 'LEAVE_REQUEST', origin: 'USER', status: 'PENDING', requestDate: '2026-10-29T10:00:00.000Z',
  employee: { name }, affectedEmployee: null, details: {}, ...extra,
});
const alert = (id: string, name: string, extra: Partial<PresentableItem> = {}): PresentableItem & { id: string } => ({
  id, requestType: 'PUNCH_EVIDENCE_REVIEW', origin: 'SYSTEM', status: 'PENDING', requestDate: '2026-10-29T04:00:00.000Z',
  employee: null, affectedEmployee: { name }, details: { businessDate: '2026-10-29' }, ...extra,
});

describe('Review queue system alerts (screen)', () => {
  it('the Type filter offers exactly "System Requests", and punch evidence is not an ordinary request type', () => {
    expect(SYSTEM_REQUESTS_LABEL).toBe('System Requests');
    expect(USER_REQUEST_TYPES.map(([v]) => v)).not.toContain('PUNCH_EVIDENCE_REVIEW');
    expect(component).toContain('<option value="">All request types</option>');
    expect(component).toContain('<option value={SYSTEM_REQUESTS_FILTER}>{SYSTEM_REQUESTS_LABEL}</option>');
    expect(component).not.toMatch(/Punch Evidence Review/);
    expect(queueOrigin('')).toBe('default');
    expect(queueOrigin('LEAVE_REQUEST')).toBe('default');
    expect(queueOrigin(SYSTEM_REQUESTS_FILTER)).toBe('system');
  });

  it('every ordinary request type the backend knows is offered, with the same label', () => {
    for (const [value, label] of USER_REQUEST_TYPES) expect(REVIEW_TYPE_LABEL[value as keyof typeof REVIEW_TYPE_LABEL]).toBe(label);
    const backendUserTypes = Object.keys(REVIEW_TYPE_LABEL).filter((t) => t !== 'PUNCH_EVIDENCE_REVIEW');
    expect(USER_REQUEST_TYPES.map(([v]) => v).sort()).toEqual(backendUserTypes.sort());
    expect(REVIEW_TYPE_LABEL.PUNCH_EVIDENCE_REVIEW).toBe('Punch Evidence Alert');
  });

  it('the API client asks for system alerts only when the filter says so', () => {
    expect(api).toMatch(/origin === 'system' \? \{ scope, origin \} : \{ scope \}/);
    expect(component).toMatch(/queryKey: \['unified-review-queue', scope, origin\]/);
    expect(component).toMatch(/getUnifiedReviewQueue\(scope, origin\)/);
  });

  it('11. system rows render a System badge and the system columns', () => {
    expect(SYSTEM_COLUMNS).toEqual(['Source', 'Affected Employee', 'Alert', 'Business Date', 'Punch Type', 'Status']);
    expect(component).toMatch(/function SystemBadge\(\)[\s\S]*?>System<\/span>/);
    expect(component).toMatch(/<td className="px-4 py-4"><SystemBadge \/><\/td>/);
    expect(component).toContain("{field('Source', 'System')}");
    expect(component).toContain("{field('Generated by', 'Attendance Validation Engine')}");
    expect(component).toContain("{field('Affected Employee'");
    expect(statusLabel({ origin: 'SYSTEM', status: 'PENDING' })).toBe('Needs Review');
    expect(statusLabel({ origin: 'SYSTEM', status: 'APPROVED' })).toBe('Reviewed');
    expect(statusLabel({ origin: 'SYSTEM', status: 'REJECTED' })).toBe('Dismissed');
    expect(statusOptions(true).map(([, l]) => l)).toEqual(['Needs Review', 'Reviewed', 'Dismissed']);
    expect(actionLabels({ origin: 'SYSTEM' })).toEqual({ approve: 'Mark Reviewed', reject: 'Dismiss with Reason' });
  });

  it('12. a system alert is never presented as raised by the employee', () => {
    // The system table has no Name / Employee ID / requester column, and the
    // alert dialog never labels the person "Employee" or "Raised by".
    const systemModal = component.slice(component.indexOf('function SystemAlertModal'), component.indexOf('function TransferPicker'));
    expect(systemModal).not.toMatch(/'Employee'|Raised by|Requested by|Requester|>Approve<|>Reject<|Transfer To/);
    const tableStart = component.indexOf('aria-label="System alerts"');
    const systemTable = component.slice(tableStart, component.indexOf('      ) : (', tableStart));
    expect(systemTable).not.toMatch(/Employee ID|EmployeeIdentity|Transfer To|'APPROVE'|'REJECT'/);
    expect(systemTable).toContain('<AffectedEmployee item={item} />');
    expect(subjectName(alert('a', 'Vivek Mehta'))).toBe('Vivek Mehta');
    // Existing requests keep their labels.
    expect(statusLabel({ origin: 'USER', status: 'PENDING' })).toBe('Pending');
    expect(actionLabels({ origin: 'USER' })).toEqual({ approve: 'Approve', reject: 'Reject' });
  });

  it('Dismiss needs a reason in the dialog before it can be sent', () => {
    expect(component).toMatch(/disabled=\{review\.isPending \|\| !reason\.trim\(\)\}[^>]*onClick=\{\(\) => review\.mutate\('DISMISS'\)\}/);
    expect(component).toMatch(/reviewSystemAlert\(item, 'MARK_REVIEWED'\)/);
  });

  it('4, 9. filtering: system alerts never pass the default filter; the name search reads the affected employee', () => {
    const items = [request('l-1', 'Asha Rao'), alert('p-1', 'Vivek Mehta'), alert('p-2', 'Asha Rao')];
    expect(filterQueueItems(items, DEFAULT_FILTERS).map((i) => i.id)).toEqual(['l-1']);
    expect(filterQueueItems(items, { ...DEFAULT_FILTERS, status: '' }).map((i) => i.id)).toEqual(['l-1']);
    const system = { ...DEFAULT_FILTERS, type: SYSTEM_REQUESTS_FILTER };
    expect(filterQueueItems(items, system).map((i) => i.id)).toEqual(['p-1', 'p-2']);
    expect(filterQueueItems(items, { ...system, name: 'vivek' }).map((i) => i.id)).toEqual(['p-1']);
    expect(filterQueueItems(items, { ...system, name: 'asha' }).map((i) => i.id)).toEqual(['p-2']);
    expect(filterQueueItems(items, { ...system, status: 'APPROVED' })).toEqual([]);
    expect(filterQueueItems(items, { ...system, date: '2026-10-29' })).toHaveLength(2);
  });

  it('21. clearing the filter returns to the default employee-request queue', () => {
    expect(DEFAULT_FILTERS).toEqual({ date: '', name: '', type: '', status: 'PENDING' });
    expect(queueOrigin(DEFAULT_FILTERS.type)).toBe('default');
    expect(component).toMatch(/const resetAdditionalFilters = \(\) => \{\s*setNameFilter\(DEFAULT_FILTERS\.name\);\s*setTypeFilter\(DEFAULT_FILTERS\.type\);\s*setStatusFilter\(DEFAULT_FILTERS\.status\);/);
    expect(activeFilterCount({ ...DEFAULT_FILTERS, type: SYSTEM_REQUESTS_FILTER })).toBe(activeFilterCount(DEFAULT_FILTERS) + 1);
    // The filter bar is reachable even when the default list is empty.
    expect(component).not.toContain("if (!queue.data?.items.length) return");
  });

  it('22. the filter panel and the system table stay usable on narrow and wide screens', () => {
    // The panel never exceeds the viewport, and both tables scroll inside their own frame.
    expect(component).toContain('w-[min(20rem,calc(100vw-2rem))]');
    expect(component).toMatch(/overflow-x-auto rounded-xl border-2 border-violet-300[\s\S]*?min-w-\[980px\]/);
    // The alert dialog stacks its fields to one column on a phone.
    expect(component).toContain('grid grid-cols-1 gap-x-5 gap-y-3 rounded-xl bg-slate-50 p-4 sm:grid-cols-2');
  });
});
