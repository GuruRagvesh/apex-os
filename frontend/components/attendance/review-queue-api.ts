import { api, unwrap as r } from '@apex/shared-auth';

export type UnifiedRequestType =
  | 'ATTENDANCE_CORRECTION'
  | 'LEAVE_REQUEST'
  | 'DEPARTMENT_ROLE_TRANSFER'
  | 'PUNCH_EVIDENCE_REVIEW'
  | 'RETENTION_RULE_PROPOSAL'
  | 'LEGAL_HOLD_REQUEST'
  | 'FNF_ADJUSTMENT_REQUEST';

export interface UnifiedReviewItem {
  id: string;
  applicationId: string;
  requestType: UnifiedRequestType;
  requestTypeLabel: string;
  subjectUserId: string | null;
  employee: {
    id: string;
    employeeId: string | null;
    name: string;
    avatar: string | null;
    photoUrl: string | null;
    designation: string | null;
    role: { name: string } | null;
    department: { id: string; name: string } | null;
  } | null;
  reason: string;
  requestDate: string;
  status: 'PENDING' | 'APPROVED' | 'REJECTED';
  sourceStatus: string;
  details: Record<string, unknown>;
  assignedReviewer: { id: string; employeeId: string | null; name: string } | null;
  /** USER: raised by a person. SYSTEM: generated by the attendance validation engine. */
  origin: 'USER' | 'SYSTEM';
  generatedBy: 'ATTENDANCE_VALIDATION_ENGINE' | null;
  /** Always null for a system alert. */
  requester: ReviewQueuePerson | null;
  /** System alerts only: who the alert is about. */
  affectedEmployee: ReviewQueuePerson | null;
  requiresApproval: boolean;
  reviewActions: Array<'APPROVE' | 'REJECT' | 'MARK_REVIEWED' | 'DISMISS'>;
}

export interface ReviewQueuePerson {
  id: string;
  employeeId: string | null;
  name: string;
  department: string | null;
}

export interface ForwardCandidate {
  id: string;
  employeeId: string | null;
  name: string;
  role: string;
  department: { id: string; name: string } | null;
}

export interface UnifiedQueueResponse {
  scope: 'team' | 'company';
  origin: 'default' | 'system';
  total: number;
  items: UnifiedReviewItem[];
}

export interface UnifiedQueueCounts {
  team: number;
  company: number;
  /** Pending system alerts; 0 for anyone who may not see them. */
  system: number;
  canViewCompany: boolean;
}

const key = (value: string) => encodeURIComponent(value);

/**
 * The official status an approved "incorrect attendance status" correction may
 * grant. The server refuses an approval of that type without one, and holds it
 * for HR when the day cannot take the granted status.
 */
export type GrantedAttendanceStatus = 'PRESENT' | 'HALF_DAY';
export const GRANTED_STATUS_OPTIONS: Array<{ value: GrantedAttendanceStatus; label: string }> = [
  { value: 'PRESENT', label: 'Present' },
  { value: 'HALF_DAY', label: 'Half Day' },
];

/** True when approving this item needs a granted status. */
export function needsGrantedStatus(item: Pick<UnifiedReviewItem, 'requestType' | 'details'>): boolean {
  return item.requestType === 'ATTENDANCE_CORRECTION' && item.details?.policyCorrectionType === 'INCORRECT_ATTENDANCE_STATUS';
}

/** The default list never contains system alerts; `system` returns only them. */
export async function getUnifiedReviewQueue(scope: 'team' | 'company', origin: 'default' | 'system' = 'default'): Promise<UnifiedQueueResponse> {
  return r(api.get('/review-queue', { params: origin === 'system' ? { scope, origin } : { scope } }));
}

export async function getUnifiedReviewCounts(): Promise<UnifiedQueueCounts> {
  return r(api.get('/review-queue/counts'));
}

export async function getForwardCandidates(type: UnifiedRequestType, id: string): Promise<{ items: ForwardCandidate[] }> {
  return r(api.get(`/review-queue/${key(type)}/${key(id)}/forward-candidates`));
}

export async function decideUnifiedRequest(
  item: Pick<UnifiedReviewItem, 'requestType' | 'id'>,
  decision: 'APPROVE' | 'REJECT',
  reason?: string,
  grantedStatus?: GrantedAttendanceStatus,
) {
  return r(api.patch(`/review-queue/${key(item.requestType)}/${key(item.id)}/decision`, { decision, reason, grantedStatus }));
}

/** Mark Reviewed or Dismiss a system alert. Dismiss needs a reason. Attendance is never changed. */
export async function reviewSystemAlert(
  item: Pick<UnifiedReviewItem, 'requestType' | 'id'>,
  action: 'MARK_REVIEWED' | 'DISMISS',
  reason?: string,
) {
  return r(api.patch(`/review-queue/${key(item.requestType)}/${key(item.id)}/decision`, { action, reason }));
}

export async function forwardUnifiedRequest(
  item: Pick<UnifiedReviewItem, 'requestType' | 'id'>,
  reviewerId: string,
  reason?: string,
) {
  return r(api.patch(`/review-queue/${key(item.requestType)}/${key(item.id)}/forward`, { reviewerId, reason }));
}
